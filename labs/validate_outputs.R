# Independent CSV/data-shape/derived-output checks. No model re-estimation.
args <- commandArgs(trailingOnly = FALSE)
script_arg <- grep("^--file=", args, value = TRUE)
if (length(script_arg) != 1L) stop("Run this saved file with Rscript.")
lab_dir <- dirname(normalizePath(sub("^--file=", "", script_arg), winslash = "/", mustWork = TRUE))
read_output <- function(name) read.csv(file.path(lab_dir, name), check.names = FALSE)
s <- read_output("synthetic_sport.csv")
w <- read_output("synthetic_school_wide.csv")
l <- read_output("synthetic_school_long.csv")
r <- read_output("results.csv")
d <- read_output("invariance_comparisons.csv")
p <- read_output("regression_paths.csv")
t <- read_output("time_basis.csv")
checks <- list()
check <- function(name, condition, detail) {
  checks[[length(checks) + 1L]] <<- data.frame(check = name, passed = isTRUE(condition), detail = detail)
  if (!isTRUE(condition)) stop("FAILED: ", name)
}
check("row_counts", nrow(s) == 300 && nrow(w) == 500 && nrow(l) == 2000, "300 sport; 500 school wide; 2000 school long")
check("synthetic_flags", all(s$synthetic) && all(w$synthetic) && all(l$synthetic), "every record is explicitly synthetic")
check("unique_keys", !anyDuplicated(s$id) && !anyDuplicated(w$id) && !anyDuplicated(paste(l$id, l$time)), "wide ID unique; long (ID,time) unique")
check("missing_code_metadata", all(s$missingCode == -9) && all(w$missingCode == -9) && all(l$missingCode == -9), "-9 is code metadata, not a modeled variable")
check("elite_is_not_sex", !identical(w$elite, w$sex) && all(w$elite %in% 0:1) && all(w$sex %in% 0:1), "distinct synthetic covariates")
for (wave in 0:3) {
  long_rows <- l[l$time == wave, ]
  index <- match(w$id, long_rows$id)
  wide_values <- unname(as.matrix(w[, paste0("psc_t", wave, "_", 1:3)]))
  long_values <- unname(as.matrix(long_rows[index, paste0("psc_", 1:3)]))
  check(paste0("reshape_wave_", wave), identical(wide_values, long_values), "long/wide values match exactly including -9")
  check(paste0("age_time_wave_", wave), identical(long_rows$age[index], w$age + wave) && all(long_rows$baseline_age[index] == w$age), "age=baseline_age+time")
}
check("model_integrity", nrow(r) == 12 && !anyDuplicated(r$id) && all(r$converged) && all(r$estimator == "MLR"), "12 successful MLR model rows")
check("finite_fit_measures", all(is.finite(as.matrix(r[, c("cfi", "rmsea", "srmr", "df", "chisq", "pvalue")]))), "no unavailable/nonfinite displayed fit measures")
check("model_n", all(r$n[r$dataset == "sport"] == 300) && all(r$n[r$dataset == "school"] == 500), "reported N matches source row counts")
from <- match(d$from, r$id)
to <- match(d$to, r$id)
check("delta_cfi_direction", nrow(d) == 6 && max(abs(d$deltaCFI - (r$cfi[to] - r$cfi[from]))) < 1e-10, "restricted minus less restricted")
check("delta_rmsea_direction", max(abs(d$deltaRMSEA - (r$rmsea[to] - r$rmsea[from]))) < 1e-10, "restricted minus less restricted")
check("path_intervals", nrow(p) == 7 && all(p$ci.lower <= p$est & p$est <= p$ci.upper) && all(p$se > 0), "3 SEM paths and 4 MIMIC paths; finite positive SE and ordered CI")
check("time_prediction_identity", max(abs(t$predicted_baseline_coding - t$predicted_last_coding)) < 1e-10 && max(abs(t$predicted_baseline_coding - (t$baseline_intercept + t$time * t$slope))) < 1e-10, "shifting time origin preserves predicted values")
basis <- as.matrix(t[, c("orthogonal_linear", "orthogonal_quadratic")])
check("orthogonal_basis", max(abs(crossprod(basis) - diag(2))) < 1e-10 && max(abs(colSums(basis))) < 1e-10, "orthonormal linear/quadratic coding; no polynomial model fitted")
record <- do.call(rbind, checks)
write.table(record, file.path(lab_dir, "data_quality_checks.csv"), sep = ",", row.names = FALSE, quote = TRUE, fileEncoding = "UTF-8")
cat("PASS:", nrow(record), "independent data and derived-result checks.\n")
